// 100行超: 免責文言の転記（v2 §1.1 / §1.3 / §9 / §10 / §12）。**文言は仕様書が単一ソース**
// なので要約せず全文を持つ。分割すると出典との対応が追いにくくなるため 1 ファイルに置く。
//
// 出力に「税務上の所得金額」とは書かない（v2 §1.1）。本ツールが出すのは
// 「bitbank 口座における取引集計・税計算用参考データ」。
//
// **限界は「単一取引所だから」ではなく「口座外に同一銘柄があるとき」**。
// bitbank だけで完結している銘柄なら bitbank のデータが全体そのもので、譲渡原価は
// 正しく出る。これは v2 §1.2 の表示ガードが体現している条件そのもの（(a) アテステーション
// = 口座外に保有・取引が無い旨の申告）で、無条件に「原理的に計算できない」と書くと
// **自分のガードを否定し、bitbank だけで取引している利用者の数値まで無効に見せる**。
import type { Method } from "../schema/method.js";
import type { Taxation } from "../schema/taxation.js";

export const POSITIONING =
  "本レポートは「bitbank 口座における取引集計・税計算用参考データ」であり、" +
  "税務上の所得金額ではありません。総平均法・移動平均法は納税者が保有する同一種類の" +
  "暗号資産全体（全取引所・全ウォレット横断）について計算します。同一銘柄を bitbank " +
  "口座の外でも保有・取引されている場合、本レポートの数値だけでは正確な譲渡原価に" +
  "なりません（該当する銘柄は参考損益を表示しません）。bitbank 口座だけで完結している" +
  "銘柄については、その旨のご申告と残高突合の一致を条件に参考損益を表示します。";

export const OUT_OF_SCOPE = [
  "他社取引所・ウォレット・DeFi・NFT の損益、bitbank 外での決済使用・贈与等",
  "所得区分の最終判定、申告要否の判定、税額計算",
  "確定申告書の作成",
] as const;

/** v2 §9【方針】の固定注記（本文はそのまま転記。末尾の括弧だけ対象年を埋める）。 */
const AGGREGATION_BODY =
  "本金額は当社（bitbank）における暗号資産取引の参考損益であり、所得区分が雑所得" +
  "（その他雑所得）となる場合、他の取引所・ウォレットの損益、暗号資産以外の雑所得と" +
  "合算した上で雑所得の金額が計算されます。雑所得の損失は給与所得等と通算できず、" +
  "翌年へ繰り越せません";

/**
 * `futureRegime` と同じ理由で対象年を埋める。v2 §9 の転記は末尾が「（2026年分・現行制度）」
 * 固定で、`--year=2027` だと**別の年の制度を対象年の説明として出す**ことになる。
 * `projected` の年は現行制度と言い切れないので、計算の前提だと分かる書き方にする
 * （`futureRegime` の「総合課税を前提に計算しています」と揃える）。
 */
export function aggregationNote(taxation: Taxation, year: number): string {
  const premise = taxation.certainty === "settled" ? "現行制度" : "総合課税を前提";
  return `${AGGREGATION_BODY}（${year}年分・${premise}）。`;
}

/** v2 §10【方針】の免責文言テンプレート（そのまま転記）。 */
export const TWENTY_MAN_RULE =
  "本レポートの参考損益が20万円以下であっても、確定申告が不要になるとは限りません。" +
  "所得税の確定申告不要制度（いわゆる「20万円ルール」）は、給与収入2,000万円以下・" +
  "1か所給与・年末調整済み等の条件を満たす方について、給与所得・退職所得以外の" +
  "所得金額の合計額（他の取引所・ウォレットでの損益や副業等の所得を含みます。ただし、" +
  "申告不要を選択した一定の配当所得・源泉徴収あり特定口座内の株式等譲渡所得や、" +
  "源泉分離課税の所得など、法令上この判定に含まれない所得を除きます）が20万円以下の" +
  "場合に、所得税の確定申告を不要とする制度です。この場合でも住民税の申告は市区町村へ" +
  "別途必要です。また、医療費控除等のため確定申告を行う場合には、20万円以下の所得も" +
  "すべて申告に含める必要があります。詳細は国税庁タックスアンサー No.1900 を" +
  "ご確認ください。";

/**
 * v2 §12 のレポート注記。**対象年を埋める**（元は「2026年分」がハードコードされており、
 * `--year=2027` を渡すと事実と食い違う文言が出ていた）。
 * `projected` の年は「適用されません」と言い切れないので、そこだけ表現を変える。
 */
export function futureRegime(taxation: Taxation, year: number): string {
  const head = "暗号資産の課税方式を見直す法改正が成立していますが（2026年7月時点）、";
  const tail = "適用開始時期・対象範囲は今後の政省令等で確定します。";
  return taxation.certainty === "settled"
    ? `${head}本レポートが対象とする${year}年分には適用されません。${tail}`
    : `${head}本レポートが対象とする${year}年分に適用されるかは施行日により確定します。` +
        `本レポートは総合課税を前提に計算しています。${tail}`;
}

/**
 * 出力層の表示丸めの説明（v2 §3【方針】・ADR-005）。**末尾だけ転記から変えている**:
 * v2 §3 は「国税庁計算書互換モードは別途提供予定です」で終わるが、互換欄は実装済みで、
 * 参考損益を出せた銘柄には同じレポートに `nta_compat` が並ぶ（`report/currency.ts`）。
 * 転記のままだと「互換値はまだ無い」と読めて**出力自身と食い違う**ので実装状態に合わせた
 * （`aggregationNote` / `futureRegime` と同じ理由の逸脱）。
 */
export const ROUNDING_NOTE =
  "内部計算は厳密値（有理数）で行い、丸めは表示時に 1 回だけ適用しています" +
  "（円未満切捨て）。各項目を独立に丸めるため、表示上の「収入金額計 − 必要経費計」と" +
  "「参考損益」が 1 円ずれることがあります。国税庁計算書と同じ丸め位置で計算した欄は、" +
  "参考損益を表示した銘柄に nta_compat として併記しています。";

/**
 * 移動平均法のときだけ足す注記。計算書は**繰越価額・購入価額が整数円入力**である前提で
 * 組まれていて（付録D.5 / D.3）、そこが崩れると「シートに書いたらこうなる」値でなくなる。
 * 販売所（即時売買）は約定代金の列が無く `数量 × 指値価格` で出すため小数円が生じるので、
 * 互換欄はその確定を挟んでいる。総平均法には無関係なので常時は載せない。
 */
export const SHEET_INPUT_NOTE =
  "移動平均法の nta_compat は、国税庁計算書が整数円入力を前提とするため" +
  "（付録D.5）、繰越価額と購入価額を円へ確定（四捨五入）してから計算しています。" +
  "販売所（即時売買）の約定は「数量 × 指値価格」で小数円になるため、この確定が" +
  "入る銘柄があります。既定の計算（非丸め）はこの確定を行いません。";

/** 年間取引報告書との突合用。差の有無は「取込の網羅性」の話で、税務上の正しさではない。 */
export const VERIFY_NOTE =
  "本突合は取込データの網羅性を確認するもので、税務上の正しさを保証するものでは" +
  "ありません。差がゼロであっても、bitbank 口座外の取引・保有は反映されていません。";

export function verifyDisclaimers(): string[] {
  return [POSITIONING, VERIFY_NOTE];
}

/**
 * レポート末尾に載せる免責の並び。`method` を受けるのは `SHEET_INPUT_NOTE` のためだけで、
 * 総平均法（既定）に無関係な注記を常時載せない。省略時は載せない側に倒す。
 */
export function disclaimers(taxation: Taxation, year: number, method?: Method): string[] {
  return [
    POSITIONING,
    `スコープ外: ${OUT_OF_SCOPE.join(" / ")}`,
    aggregationNote(taxation, year),
    TWENTY_MAN_RULE,
    futureRegime(taxation, year),
    ROUNDING_NOTE,
    ...(method === "moving-average" ? [SHEET_INPUT_NOTE] : []),
  ];
}
